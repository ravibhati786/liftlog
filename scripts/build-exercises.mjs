// Builds js/exercises.js from openGym's copy of the exercises-dataset metadata (MIT, see NOTICE.md).
// Only needed to change the library. Usage (needs a clone of github.com/DuarteSantos8/openGym):
//   node scripts/build-exercises.mjs <openGym>/frontend/src/lib/exercises-data.js
import { readFileSync, writeFileSync } from 'node:fs'
import { PLANS } from '../js/plans.js'

const src = readFileSync(process.argv[2], 'utf8')
const db = JSON.parse(src.match(/export const EXDB=(\[.*?\]);?\s*(\n|$)/s)[1])

const GYM_EQ = new Set(['barbell', 'dumbbell', 'cable', 'leverage machine', 'body weight', 'sled machine', 'smith machine', 'ez barbell', 'kettlebell', 'weighted', 'assisted', 'trap bar', 'olympic barbell', 'rope', 'stationary bike', 'elliptical machine', 'stepmill machine', 'upper body ergometer', 'skierg machine'])
const SKIP = /stretch|v\. ?\d|\(female\)|\(male\)|on stability ball|with arm blaster|back pov/
const planIds = new Set(PLANS.flatMap(p => p.days.flatMap(d => d.ex.map(e => e.id))))

const NAME = { '2135': 'front plank', '0203': 'cable face pull / rear delt row', '2330': 'cable lat pulldown', '0739': '45° leg press', '0227': 'cable chest fly', '0200': 'cable rope pushdown', '0194': 'cable overhead triceps extension', '0060': 'barbell skull crusher', '0410': 'dumbbell split squat', '3666': 'incline treadmill walk', '0861': 'cable seated row' }
const cap = s => s.charAt(0).toUpperCase() + s.slice(1)

const out = db
  .filter(e => planIds.has(e.id) || (GYM_EQ.has(e.eq) && !SKIP.test(e.n)))
  .map(e => ({ id: e.id, n: cap(NAME[e.id] || e.n), bp: e.bp, eq: e.eq, tg: e.tg, sm: e.sm, st: e.st, gif: e.gif }))
  .sort((a, b) => a.n.localeCompare(b.n))

const missing = [...planIds].filter(id => !out.some(e => e.id === id))
if (missing.length) throw new Error('Plan uses unknown exercise ids: ' + missing)

writeFileSync(new URL('../js/exercises.js', import.meta.url),
  '// GENERATED by scripts/build-exercises.mjs — do not edit by hand.\n' +
  '// Names, muscles and instructions: ExerciseDB v1 via hasaneyldrm/exercises-dataset (MIT).\n' +
  'export const EXERCISES = ' + JSON.stringify(out) + '\n')
console.log(out.length, 'exercises')
